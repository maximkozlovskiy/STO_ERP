import { SetMetadata } from '@nestjs/common';

/**
 * Ключ метаданих для позначки «публічний роут».
 *
 * Архітектура «закрито за замовчуванням» (рішення власника 2026-10-24): `JwtAuthGuard`
 * зареєстрований глобально (`APP_GUARD` у `app.module.ts`), тож КОЖЕН роут вимагає JWT,
 * доки його явно не позначено `@Public()`. Роут без guard-а й без `@Public()` «падає закрито».
 */
export const IS_PUBLIC_KEY = 'isPublic';

/**
 * Позначає роут (метод) або контролер (клас) як публічний — глобальний `JwtAuthGuard`
 * пропускає його без автентифікації. Список публічних роутів навмисно короткий і
 * стережеться контракт-тестом `auth-global-guard.contract.spec.ts`: будь-який новий
 * `@Public()` поза дозволеним списком валить тест у CI.
 */
export const Public = () => SetMetadata(IS_PUBLIC_KEY, true);
