/**
 * Нормалізує артикул/код товару для порівняння при Excel-імпорті.
 *
 * `(s ?? '').toUpperCase().replace(/[^A-Z0-9]/g, '')` — верхній регістр + прибирання всіх
 * символів окрім латинських літер і цифр. Дефіси, пробіли, крапки, слеші зникають, тож
 * `'04E-129-620'`, `'04E 129 620'`, `'04e.129/620'` → однаковий ключ `'04E129620'`.
 *
 * Кирилиця також прибирається (`[^A-Z0-9]`) — це навмисно: артикули запчастин у постачальників
 * латиниця+цифри, а кириличні «назви» не є артикулами й не мають брати участь у exact-матчі коду.
 *
 * null/undefined/порожній рядок → `''` (беззбитково для callers, які фільтрують порожнє).
 */
export function normalizeArticle(s: string | null | undefined): string {
  return (s ?? '').toUpperCase().replace(/[^A-Z0-9]/g, '');
}
