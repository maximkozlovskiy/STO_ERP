/**
 * SECURITY: нейтралізація formula-injection у клітинці XLSX (CWE-1236).
 * Рядок, що починається з `= + - @` (TAB/CR), Excel може виконати як формулу. Експорт документів
 * і публічний кошторис несуть вільний текст із БД (назви організації, товарів, робіт, примітки) —
 * такий рядок префіксуємо `'`. Числа й не-рядки не чіпаємо.
 */
export function xlsxSafe<T>(v: T): T | string {
  if (typeof v === 'string' && /^[=+\-@\t\r]/.test(v)) return `'${v}`;
  return v;
}
