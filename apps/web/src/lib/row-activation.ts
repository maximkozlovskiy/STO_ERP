/**
 * Єдиний стандарт кліку по рядку списку з боковою панеллю.
 *
 *   панель УВІМКНЕНА → клік вибирає рядок (панель показує його);
 *                      повторний клік по тому самому рядку знімає вибір (панель ховається);
 *   панель ВИМКНЕНА  → клік відкриває документ / картку.
 *
 * Олівець у рядку і кнопка «Відкрити …» у панелі відкривають документ завжди й цієї функції
 * не потребують. Правило живе тут, щоб списки не розходились: до 2026-10-13 рахунки відкривали
 * картку одразу, наряди з вимкненою панеллю не робили нічого, а склад уже працював за стандартом.
 */
export interface RowActivation {
  /** Чи увімкнена бокова панель списку. */
  panelEnabled: boolean;
  /** Чи цей рядок уже вибраний (показаний у панелі). */
  isSelected: boolean;
  /** Вибрати рядок — показати його в панелі. */
  select: () => void;
  /** Зняти вибір — сховати панель. */
  deselect: () => void;
  /**
   * Відкрити документ / картку. Не задано — у списку немає картки (залишки складу):
   * з вимкненою панеллю клік нічого не робить.
   */
  open?: () => void;
}

export function activateRow({ panelEnabled, isSelected, select, deselect, open }: RowActivation) {
  if (!panelEnabled) {
    open?.();
    return;
  }
  if (isSelected) deselect();
  else select();
}
