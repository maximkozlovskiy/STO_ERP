-- BR-WO-017: видалення наряду позначає видаленими його записи календаря (рішення власника 2026-10-16).
--
-- До цієї зміни запис календаря видаленого наряду лишався живим: його видно в календарі з номером
-- наряду, і він займав підйомник і механіка (EXCLUDE `calendar_slots_no_overlap`, перевірка
-- зайнятості) — новий запис у цей час давав «підйомник зайнятий». Тепер `WorkOrdersService.remove`
-- позначає записи в тій самій транзакції; ця міграція вирівнює записи, видалені раніше.
--
-- Лише дані, схема не змінюється. Ідемпотентно: чіпає тільки живі записи вже видалених нарядів
-- (на dev-базі 2026-10-16 таких 0).

UPDATE "calendar_slots" AS s
SET "deletedAt" = w."deletedAt",
    "syncVersion" = s."syncVersion" + 1
FROM "work_orders" AS w
WHERE s."workOrderId" = w."id"
  AND w."deletedAt" IS NOT NULL
  AND s."deletedAt" IS NULL;
