-- BR-WO-022: скасування наряду позначає видаленими його записи календаря (рішення власника 2026-10-18).
--
-- До цієї зміни запис календаря скасованого наряду лишався живим. Тепер його не показує
-- `GET /calendar/slots` і не бачить перевірка зайнятості (`OF_LIVE_WORK_ORDER`), але EXCLUDE
-- `calendar_slots_no_overlap` бачить лише `deletedAt IS NULL` — такий запис і далі тримав би
-- підйомник: новий запис у цей час отримував би 409 «хтось щойно зайняв» на вільному з вигляду
-- підйомнику. Ще його рахували онлайн-запис (`BookingService`, зайнятість дня) і звіт
-- завантаження постів, а планшет отримував його живим. `WorkOrdersService.transition` позначає
-- записи в тій самій транзакції; ця міграція вирівнює записи нарядів, скасованих раніше.
--
-- Лише дані, схема не змінюється. Ідемпотентно: чіпає тільки живі записи вже скасованих нарядів.
-- `deletedAt` — момент скасування невідомий, тож `updatedAt` наряду (останній запис у наряд).

UPDATE "calendar_slots" AS s
SET "deletedAt" = w."updatedAt",
    "syncVersion" = s."syncVersion" + 1
FROM "work_orders" AS w
WHERE s."workOrderId" = w."id"
  AND w."status" = 'CANCELLED'
  AND s."deletedAt" IS NULL;
