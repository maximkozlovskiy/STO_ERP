-- BR-WO-007: прибрати застарілий ПДВ у нарядів, де в сумі до сплати ПДВ немає.
--
-- Наряди, завершені до 2026-10-08 в режимі «ПДВ зверху», мають "totalNet" = "totalAmount"
-- (клієнтові ПДВ не нараховували), але в "totalVat" лишилось колись пораховане значення.
-- Через це в конструкторі звітів «Сума (без ПДВ)» + «ПДВ» ≠ «Сума з ПДВ», а ПДВ там більший,
-- ніж у звіті «Виручка». Рішення власника (2026-10-08): обнулити міграцією.
--
-- Умова не залежить від статусу: якщо сума без ПДВ дорівнює сумі до сплати, ПДВ у сумі немає
-- за визначенням інваріанта "totalNet" + "totalVat" = "totalAmount". Після міграції інваріант
-- виконується для всіх нарядів. Ідемпотентно: повторний запуск нічого не змінює.

UPDATE "work_orders"
SET "totalVat" = 0,
    "syncVersion" = "syncVersion" + 1
WHERE "totalNet" = "totalAmount"
  AND "totalVat" <> 0;
